def _gvariant_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def gnome_override(plan: Plan) -> str:
    """GSettings defaults: wallpaper, lock screen, login logo and accent colour.

    Ubuntu's own overrides are scoped to its session (``[schema:ubuntu]``),
    and desktop-scoped values beat plain ones, so on Ubuntu every section is
    written twice: once plain and once scoped.
    """
    uri = _gvariant_string("file://" + plan.wallpaper_path)
    sections: dict[str, dict[str, str]] = {
        "org.gnome.desktop.background": {
            "picture-uri": uri,
            "picture-uri-dark": uri,
            "picture-options": "'zoom'",
        },
        "org.gnome.desktop.screensaver": {"picture-uri": uri, "picture-options": "'zoom'"},
        "org.gnome.login-screen": {"logo": _gvariant_string(f"/usr/share/pixmaps/{LOGO_NAME}.png")},
    }
    if plan.gnome_accent:
        sections["org.gnome.desktop.interface"] = {"accent-color": _gvariant_string(plan.gnome_accent)}
    return _override_text(plan, sections, [""] + ([":ubuntu"] if plan.base.id == "ubuntu" else []))


def cinnamon_override(plan: Plan) -> str:
    """GSettings defaults: wallpaper (also the lock screen's) and the menu button logo.

    The menu applet shows ``app-menu-icon-name`` unless a user picks their own
    icon. Cinnamon has no accent-colour setting; its themes fix the colours.
    Distro packages may set these keys scoped to the Cinnamon session
    (``X-Cinnamon``), so every section is also written scoped.
    """
    uri = _gvariant_string("file://" + plan.wallpaper_path)
    sections = {
        "org.cinnamon.desktop.background": {"picture-uri": uri, "picture-options": "'zoom'"},
        "org.cinnamon": {"app-menu-icon-name": _gvariant_string(LOGO_NAME), "app-menu-label": "''"},
    }
    return _override_text(plan, sections, ["", ":X-Cinnamon"])


def _override_text(plan: Plan, sections: dict[str, dict[str, str]], scopes: list[str]) -> str:
    out = [header_comment(plan)]
    for scope in scopes:
        for schema in sorted(sections):
            out.append(f"[{schema}{scope}]")
            out.extend(f"{key}={value}" for key, value in sections[schema].items())
            out.append("")
    return "\n".join(out)


def add_grub_configs(ctx: BuildContext, plan: Plan, kernel: str, initrd: str, install: bool = False) -> None:
    """GRUB menu plus the two small configs that find it on BIOS and UEFI.

    With install, the menu also offers to start the live session straight into
    the installer (kernel parameter linuxlive.install, read by install-on-boot).
    """
    title = f"{plan.spec.name} {plan.spec.version}"
    args = plan.kernel_args
    install_entry = f"""
menuentry 'Install {title}' --id install {{
	linux {kernel} linuxlive.install {args}
	initrd {initrd}
}}
""" if install else ""
    menu = header_comment(plan) + f"""
set default=0
set timeout=5
set timeout_style=menu

menuentry 'Try {title}' --id try {{
	linux {kernel} {args}
	initrd {initrd}
}}
{install_entry}
menuentry 'Try {title} (safe graphics)' --id safe {{
	linux {kernel} nomodeset {args}
	initrd {initrd}
}}

if [ "$grub_platform" = "efi" ]; then
	menuentry 'UEFI firmware settings' --id uefi-firmware {{
		fwsetup
	}}
fi
"""
    ctx.add_text("iso/boot/grub/grub.cfg", menu)
    find = f"search --no-floppy --set=root --file /{plan.marker}\nset prefix=($root)/boot/grub\n"
    # Embedded in the BIOS core image; normal mode then loads $prefix/grub.cfg.
    ctx.add_text("iso/bios-embed.cfg", find)
    # Read by GRUB EFI builds that look next to their own binary (Fedora's do).
    ctx.add_text("iso/efi-grub.cfg", find + "configfile $prefix/grub.cfg\n")


def add_iso_env(ctx: BuildContext, plan: Plan) -> None:
    spec = plan.spec
    ctx.add_text(
        "iso.env",
        header_comment(plan)
        + "# Read by scripts/assemble-iso.sh.\n"
        + shell_assignments(
            {
                "LL_BASE": plan.base.id,
                "LL_ID": spec.id,
                "LL_NAME": spec.name,
                "LL_VERSION": spec.version,
                "LL_BASE_LABEL": plan.base.label,
                "LL_VOLID": plan.volid,
                "LL_ISO_NAME": plan.iso_name,
                "LL_LIVE_LAYOUT": plan.live_layout,
                "LL_MARKER": plan.marker,
                "LL_FLATPAKS": " ".join(app.flatpak for app in plan.apps),
            }
        ),
    )
