"""Files every build context gets, whatever the base."""

from __future__ import annotations

import shlex

from linuxlive import __version__
from linuxlive.catalog import DATA_DIR
from linuxlive.compiler.context import BuildContext
from linuxlive.compiler.plan import LOGO_NAME, Plan
from linuxlive.png import image_info

ROOTFS_DATA = DATA_DIR / "rootfs"


def header_comment(plan: Plan, prefix: str = "#") -> str:
    s = plan.spec
    return (
        f"{prefix} Generated by linuxlive {__version__} from spec {s.id!r} "
        f"({plan.base.label}, {plan.desktop.label}).\n"
        f"{prefix} Do not edit by hand: change the spec and compile again.\n"
    )


def shell_assignments(values: dict[str, str]) -> str:
    return "".join(f"{key}={shlex.quote(value)}\n" for key, value in values.items())


def add_static_tree(ctx: BuildContext, name: str) -> None:
    """Copy data/rootfs/<name>/ into the context's rootfs/ tree."""
    root = ROOTFS_DATA / name
    if not root.is_dir():
        return
    for src in sorted(p for p in root.rglob("*") if p.is_file()):
        rel = src.relative_to(root).as_posix()
        data = src.read_bytes()
        if b"\0" not in data:
            data = data.replace(b"\r\n", b"\n")
        mode = 0o755 if rel.startswith("usr/libexec/") else 0o644
        ctx.add_bytes(f"rootfs/{rel}", data, mode=mode)


def add_branding(ctx: BuildContext, plan: Plan) -> None:
    spec = plan.spec
    accent_rgb = ",".join(str(c) for c in plan.accent_rgb) if plan.accent_rgb else ""
    ctx.add_text(
        "rootfs/usr/lib/linuxlive/branding.env",
        header_comment(plan)
        + shell_assignments(
            {
                "LL_NAME": spec.name,
                "LL_ID": spec.id,
                "LL_VERSION": spec.version,
                "LL_BASE": plan.base.id,
                "LL_BASE_LABEL": plan.base.label,
                "LL_DESKTOP": plan.desktop.id,
                "LL_WALLPAPER": plan.wallpaper_path,
                "LL_LOGO": f"/usr/share/pixmaps/{LOGO_NAME}.png",
                "LL_LOGO_ICON": LOGO_NAME,
                "LL_ACCENT_RGB": accent_rgb,
            }
        ),
    )

    ctx.add_bytes(f"rootfs{plan.wallpaper_path}", spec.branding.wallpaper.read_bytes())
    logo = spec.branding.logo.read_bytes()
    _fmt, size, _height = image_info(spec.branding.logo)
    ctx.add_bytes(f"rootfs/usr/share/pixmaps/{LOGO_NAME}.png", logo)
    ctx.add_bytes(f"rootfs/usr/share/icons/hicolor/{size}x{size}/apps/{LOGO_NAME}.png", logo)
    ctx.add_bytes("rootfs/usr/share/plymouth/themes/linuxlive/watermark.png", logo)
    ctx.add_text("rootfs/usr/share/plymouth/themes/linuxlive/linuxlive.plymouth", plymouth_theme(plan))

    add_static_tree(ctx, "common")
    add_static_tree(ctx, plan.desktop.id)
    add_static_tree(ctx, plan.base.id)
    override = {"gnome": gnome_override, "cinnamon": cinnamon_override}.get(plan.desktop.id)
    if override:
        ctx.add_text("rootfs/usr/share/glib-2.0/schemas/zz_linuxlive.gschema.override", override(plan))


