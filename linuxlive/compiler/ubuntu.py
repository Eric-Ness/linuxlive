"""Ubuntu build contexts: an apt-built container image booted live by casper."""

from __future__ import annotations

from linuxlive.compiler.common import add_grub_configs, add_install_launcher, header_comment
from linuxlive.compiler.context import BuildContext
from linuxlive.compiler.extras import build_step, packages_step
from linuxlive.compiler.plan import Plan

LIVE_USER = "live"
# Where the image keeps the bootloader .debs the installer installs (install-to-disk).
INSTALLER_DEBS = "/usr/lib/linuxlive/installer/debs"


def add_base(ctx: BuildContext, plan: Plan) -> None:
    base = plan.base
    spec = plan.spec
    ctx.add_text(
        "rootfs/etc/apt/preferences.d/linuxlive",
        header_comment(plan)
        + "# Keep these out of the image even when a metapackage recommends them.\n"
        + f"Package: {' '.join(base.blocked_packages)}\n"
        + "Pin: release a=*\n"
        + "Pin-Priority: -1\n",
    )
    # casper reads this at boot. FLAVOUR must be non-empty, or casper replaces
    # USERNAME and HOST with a name taken from the boot medium.
    ctx.add_text(
        "rootfs/etc/casper.conf",
        header_comment(plan)
        + f'export USERNAME="{LIVE_USER}"\n'
        + 'export USERFULLNAME="Live session user"\n'
        + f'export HOST="{spec.id}"\n'
        + 'export BUILD_SYSTEM="Ubuntu"\n'
        + f'export FLAVOUR="{spec.name}"\n',
    )
    ctx.add_text("rootfs/usr/share/plymouth/themes/linuxlive-text/linuxlive-text.plymouth", text_splash(plan))
    # The installer's launcher: in the menu and on the live user's desktop
    # (casper creates the live user from /etc/skel).
    add_install_launcher(ctx, plan)
    add_grub_configs(ctx, plan, kernel="/casper/vmlinuz", initrd="/casper/initrd", install=True)
    ctx.add_text("Containerfile", containerfile(plan))


def text_splash(plan: Plan) -> str:
    """Plymouth's text-mode fallback, shown when early graphics are unavailable.

    Ubuntu's own fallback (ubuntu-text) has "Ubuntu <release>" written into it
    by its package, so the spec's name needs a theme of its own.
    """
    spec = plan.spec
    accent = spec.branding.accent_color or "#ffffff"
    return f"""[Plymouth Theme]
Name={spec.name} Text
Description=Text mode boot splash for {spec.name}, generated by linuxlive
ModuleName=ubuntu-text

[ubuntu-text]
title={spec.name} {spec.version}
black=0x000000
white=0xffffff
brown=0x{accent.lstrip('#').lower()}
blue=0x8a8a8a
"""


def _apt(*commands: str) -> str:
    steps = ["set -eux", "apt-get update", *commands, "apt-get clean", "rm -rf /var/lib/apt/lists/*"]
    return "RUN " + "; \\\n    ".join(steps)


def containerfile(plan: Plan) -> str:
    base = plan.base
    image = plan.base_image
    desktop = plan.variant.packages
    return f"""{header_comment(plan)}
# Stage 1: unpack the signed Secure Boot chain (shim and GRUB) from Ubuntu's
# packages without installing them. The ISO assembler copies these binaries
# into the ISO's EFI partition.
FROM {image} AS efi
ENV DEBIAN_FRONTEND=noninteractive
RUN set -eux; \\
    apt-get update; \\
    mkdir -p /tmp/debs /x /out; \\
    chown _apt /tmp/debs; \\
    cd /tmp/debs; \\
    apt-get download {' '.join(base.efi_packages)}; \\
    for deb in ./*.deb; do dpkg-deb -x "$deb" /x; done; \\
    shim=/x/usr/lib/shim/shimx64.efi.dualsigned; \\
    if [ ! -f "$shim" ]; then shim=/x/usr/lib/shim/shimx64.efi.signed.latest; fi; \\
    cp "$shim" /out/shimx64.efi; \\
    cp /x/usr/lib/shim/mmx64.efi /out/mmx64.efi; \\
    cp /x/usr/lib/grub/x86_64-efi-signed/gcdx64.efi.signed /out/grubx64.efi

# Stage 2: the distro.
FROM {image}
ENV DEBIAN_FRONTEND=noninteractive
COPY rootfs/etc/apt/preferences.d/linuxlive /etc/apt/preferences.d/linuxlive

# Base system. The upstream container image is minimized for servers: drop
# its path excludes so new packages keep their docs and translations, and
# remove its default user so casper can create the live user.
RUN set -eux; \\
    rm -f /etc/dpkg/dpkg.cfg.d/excludes; \\
    if id ubuntu >/dev/null 2>&1; then userdel ubuntu; rm -rf /home/ubuntu; fi; \\
    apt-get update; \\
    apt-get install -y {' '.join(base.system_packages)}; \\
    locale-gen en_US.UTF-8; \\
    update-locale LANG=en_US.UTF-8; \\
    apt-get clean; \\
    rm -rf /var/lib/apt/lists/*

# Live boot, boot splash, Flatpak, then the kernel.
{_apt("apt-get install -y " + " ".join(base.live_packages), "apt-get install -y --no-install-recommends " + " ".join(base.kernel_packages))}

# Desktop: {plan.desktop.label}.
{_apt("apt-get install -y " + " ".join(desktop))}

# The installer's tools, and the bootloader it installs onto the target disk,
# kept as .debs resolved against this image so the install works offline.
{_apt("apt-get install -y " + " ".join(base.installer_packages),
      f"mkdir -p {INSTALLER_DEBS}/partial",
      f"apt-get install -y --download-only -o Dir::Cache::archives={INSTALLER_DEBS} " + " ".join(base.bootloader_packages),
      f"rm -rf {INSTALLER_DEBS}/partial {INSTALLER_DEBS}/lock",
      f"ls {INSTALLER_DEBS}/grub-efi-amd64-signed_*.deb {INSTALLER_DEBS}/shim-signed_*.deb")}
{packages_step(plan)}
# Branding and linuxlive's boot check.
COPY --from=efi /out/ /usr/lib/linuxlive/efi/
COPY rootfs/ /
{build_step(plan)}# LL_BUILD_ID (optional) names this build in os-release's BUILD_ID.
ARG LL_BUILD_ID=""
RUN /bin/sh /usr/libexec/linuxlive/finalize
"""
